const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const mainSource = fs.readFileSync(path.join(__dirname, 'main.cjs'), 'utf8')
const preloadSource = fs.readFileSync(path.join(__dirname, 'preload.cjs'), 'utf8')

test('BrowserWindow security and navigation controls are present', () => {
  assert.match(mainSource, /contextIsolation:\s*true/)
  assert.match(mainSource, /nodeIntegration:\s*false/)
  assert.match(mainSource, /sandbox:\s*true/)
  assert.match(mainSource, /webSecurity:\s*true/)
  assert.match(mainSource, /setWindowOpenHandler/)
  assert.match(mainSource, /will-navigate/)
  assert.match(mainSource, /will-attach-webview/)
  assert.match(mainSource, /isApprovedExternalUrl/)
  assert.match(mainSource, /escapeHtml/)
  assert.match(mainSource, /devTools:\s*!app\.isPackaged/)
})

test('main process lifecycle and packaged paths are explicit', () => {
  assert.match(mainSource, /requestSingleInstanceLock/)
  assert.match(mainSource, /second-instance/)
  assert.match(mainSource, /before-quit/)
  assert.match(mainSource, /will-quit/)
  assert.match(mainSource, /render-process-gone/)
  assert.match(mainSource, /safeWindowState/)
  assert.match(mainSource, /createWindow\(\)\s*\n\s*void startBackend/)
  assert.match(mainSource, /app\.asar\.unpacked/)
  assert.match(mainSource, /FlujoEngine\.exe/)
  assert.match(mainSource, /FlujoSecureExecutor\.exe/)
  assert.match(mainSource, /ffmpeg\.exe/)
  assert.match(mainSource, /ffprobe\.exe/)
  assert.match(mainSource, /manifest\.json/)
  assert.match(mainSource, /FFMPEG_NOTICES\.md/)
  assert.match(mainSource, /configuration: path\.join\(flujoDataRoot\(\), 'config'\)/)
  assert.equal(fs.existsSync(path.join(root, 'dist', 'index.html')), true)
})

test('preload exposes only the bounded backend bridge and status callback', () => {
  assert.equal((preloadSource.match(/contextBridge\.exposeInMainWorld/g) || []).length, 1)
  assert.doesNotMatch(preloadSource, /shell|child_process|fs|net/) 
  assert.match(preloadSource, /requestBackend/)
  assert.match(preloadSource, /reportError/)
  assert.match(preloadSource, /onSidecarStatus/)
  assert.match(preloadSource, /MAX_DIAGNOSTIC_BYTES/)
})
