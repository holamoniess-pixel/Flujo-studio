from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.publishing.prep import PREP_STEP_NAMES, PublishPrepPipeline, build_srt, derive_tags, lines_to_srt


class PassDecision:
    allowed = True
    status = "PASS"
    reason = "ok"
    policy_version = "test"


class FakeGuard:
    def __init__(self, decision) -> None:
        self._decision = decision

    def publish_gate(self, **kwargs):
        return self._decision


class MediaResult:
    def __init__(self, status, checksum=None, error_code=None, message=""):
        self.status = status
        self.checksum = checksum
        self.error_code = error_code
        self.message = message


def run_pipeline(bundle_root: Path, caption_generate, artifact_name="Sunset Reel") -> object:
    pipeline = PublishPrepPipeline(
        guard=FakeGuard(PassDecision()),
        media_run=lambda *a, **k: MediaResult("completed", checksum="abc123"),
        bundle_root=bundle_root,
        now=lambda: "2026-10-12T00:00:00+00:00",
        caption_generate=caption_generate,
    )
    return pipeline.run(
        run_id="prep_captions",
        artifact={"id": "artifact_1", "name": artifact_name, "status": "ready", "metadata": {}},
        modality="video",
        consent={},
    )


def steps_by_name(result) -> dict:
    return {step.name: step for step in result.steps}


def main() -> None:
    # 1. Model hook supplies tags + captions: steps are labeled model-generated.
    def model_hook(title: str, description: str) -> dict:
        assert title == "Sunset Reel"
        return {
            "tags": ["sunset", "ocean", "cinematic"],
            "caption_lines": ["Waves roll in at golden hour.", "The sun dips below the horizon."],
            "provider": "nvidia",
            "model_id": "nvidia/nemotron-3-ultra-550b-a55b",
        }

    with tempfile.TemporaryDirectory(prefix="flujo-prep-cap-") as directory:
        bundle_root = Path(directory)
        result = run_pipeline(bundle_root, model_hook)
        assert result.status == "completed", [s.as_dict() for s in result.steps]
        by_name = steps_by_name(result)
        assert "model-generated via nvidia" in by_name["metadata_package"].detail, by_name["metadata_package"].detail
        assert "generated by nvidia" in by_name["captions"].detail, by_name["captions"].detail
        srt = (bundle_root / "prep_captions" / "captions.srt").read_text(encoding="utf-8")
        assert "Waves roll in at golden hour." in srt, srt
        assert "Sunset Reel" not in srt.splitlines()[2], srt  # model lines replace the deterministic title/description split
        import json as _json

        metadata = _json.loads((bundle_root / "prep_captions" / "metadata.json").read_text(encoding="utf-8"))
        assert metadata["tags"] == ["sunset", "ocean", "cinematic"], metadata["tags"]

    # 2. No hook (no provider key configured): deterministic fallback, honestly labeled.
    with tempfile.TemporaryDirectory(prefix="flujo-prep-cap-") as directory:
        bundle_root = Path(directory)
        result = run_pipeline(bundle_root, None)
        assert result.status == "completed", [s.as_dict() for s in result.steps]
        by_name = steps_by_name(result)
        assert "deterministic local fallback" in by_name["metadata_package"].detail, by_name["metadata_package"].detail
        assert "not model-generated" in by_name["metadata_package"].detail, by_name["metadata_package"].detail
        assert "deterministic fallback" in by_name["captions"].detail, by_name["captions"].detail
        assert "not model-generated" in by_name["captions"].detail, by_name["captions"].detail
        import json as _json

        metadata = _json.loads((bundle_root / "prep_captions" / "metadata.json").read_text(encoding="utf-8"))
        assert metadata["tags"] == derive_tags("Sunset Reel"), metadata["tags"]
        srt = (bundle_root / "prep_captions" / "captions.srt").read_text(encoding="utf-8")
        assert srt == build_srt("Sunset Reel", "Prepared in Flujo Studio from Sunset Reel."), srt

    # 3. Hook raises: safe fallback, honestly labeled.
    def bad_hook(title: str, description: str) -> dict:
        raise RuntimeError("provider exploded")

    with tempfile.TemporaryDirectory(prefix="flujo-prep-cap-") as directory:
        bundle_root = Path(directory)
        result = run_pipeline(bundle_root, bad_hook)
        assert result.status == "completed", [s.as_dict() for s in result.steps]
        by_name = steps_by_name(result)
        assert "deterministic fallback" in by_name["captions"].detail, by_name["captions"].detail

    # 4. Caller-supplied tag overrides still win over the model hook.
    with tempfile.TemporaryDirectory(prefix="flujo-prep-cap-") as directory:
        bundle_root = Path(directory)
        pipeline = PublishPrepPipeline(
            guard=FakeGuard(PassDecision()),
            media_run=lambda *a, **k: MediaResult("completed", checksum="abc123"),
            bundle_root=bundle_root,
            now=lambda: "2026-10-12T00:00:00+00:00",
            caption_generate=model_hook,
        )
        result = pipeline.run(
            run_id="prep_captions",
            artifact={"id": "artifact_1", "name": "Sunset Reel", "status": "ready", "metadata": {}},
            modality="video",
            consent={},
            overrides={"tags": ["custom-tag"]},
        )
        import json as _json

        metadata = _json.loads((bundle_root / "prep_captions" / "metadata.json").read_text(encoding="utf-8"))
        assert metadata["tags"] == ["custom-tag"], metadata["tags"]
        by_name = steps_by_name(result)
        assert "caller-supplied" in by_name["metadata_package"].detail, by_name["metadata_package"].detail

    # 5. lines_to_srt keeps the deterministic timing contract.
    srt = lines_to_srt(["one", "two"])
    assert srt.startswith("1\n00:00:00,000 --> 00:00:04,000\none\n"), srt
    assert "2\n00:00:04,000 --> 00:00:08,000\ntwo\n" in srt, srt

    print("publishing_captions: passed")


if __name__ == "__main__":
    main()
